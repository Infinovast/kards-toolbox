import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import localforage from 'localforage';
import { cardDisplayTitle, cardImageUrl, type KardsCardRecord } from '../types/card';
import { cacheCardImage, getCachedCardImage, readCardImageCache, recordImageCacheBatch } from './cardImages';
import { downloadCardImage, validateCardImageUrl } from './cardImageDownload';
import { cardKeywords, cardRelations } from './cardDetails';
import { isGeneratedCard, isInBuilderPool } from './cardFilters';

const cards: KardsCardRecord[] = JSON.parse(readFileSync('public/data/cards.json', 'utf8')).cards;
const base = cards.find(card => card.cardId === '50_infantry_regiment')!;
const veteran = cards.find(card => card.cardId === '50_infantry_regiment_vet')!;
assert.equal(cardImageUrl(base, 'zh-Hans'), 'https://www.kardsplayer.com/images/card/v53/zh-Hans/50_infantry_regiment.avif');
assert.equal(cardImageUrl(veteran, 'en-EN'), 'https://www.kardsplayer.com/images/card/v53/en-EN/50_infantry_regiment_vet.avif');
assert.equal(cardImageUrl(base, 'zh-Hans', 'thumbnail'), base.thumbUrl);
assert.equal(cardImageUrl(base, 'en-EN', 'thumbnail'), 'https://www.kardsplayer.com/images/card/v53/en-EN/thumb/50_infantry_regiment.avif');
assert.deepEqual([base.json.attack, base.json.defense, base.json.operationCost], [3, 2, 1]);
assert.deepEqual([veteran.json.attack, veteran.json.defense, veteran.json.operationCost], [4, 3, 1]);
assert.equal(cardDisplayTitle(veteran, 'zh-Hans'), '第 50 步兵团（老兵）');
assert.deepEqual(cardRelations(base), [{ cardId: veteran.cardId, label: '老兵形态' }]);
assert.deepEqual(cardRelations(veteran), [{ cardId: base.cardId, label: '原卡' }]);
assert.deepEqual(cardKeywords(veteran, 'zh-Hans'), ['伏击']);
assert.deepEqual(cardKeywords(base, 'zh-Hans'), []);
assert.ok(base.json.attributes!.includes('OnlySpawnable'));
assert.ok(!isGeneratedCard(base) && isInBuilderPool(base, 'Germany', 'Britain'), 'base veteran-capable unit remains constructible');
assert.ok(isGeneratedCard(veteran) && !isInBuilderPool(veteran, 'Germany', 'Britain'));

// File signatures, not pixel/visual tests. The source serves this MIME type.
const avif = Uint8Array.from([0, 0, 0, 24, ...Buffer.from('ftypavif'), 0, 0, 0, 0, ...Buffer.from('avifmif1')]);
const avifData = await downloadCardImage(base.imageUrl!, (async () => new Response(avif, { headers: { 'content-type': 'binary/octet-stream' } })) as typeof fetch);
assert.ok(avifData.startsWith('data:image/avif;base64,'));
await assert.rejects(() => downloadCardImage(base.imageUrl!, (async () => new Response('<html>not found</html>')) as typeof fetch), /不是有效图片/);
await assert.rejects(() => downloadCardImage(base.imageUrl!, (async () => new Response('offline', { status: 404 })) as typeof fetch), /404/);
for (const url of ['file:///etc/passwd', 'https://example.com/a.avif', 'https://www.kardsplayer.com/graphql', 'https://www.kardsplayer.com/images/card/v53/zh-Hans/a.avif?url=bad']) assert.throws(() => validateCardImageUrl(url));

const memory = new Map<string, unknown>();
localforage.getItem = async <T>(key: string) => (memory.get(key) ?? null) as T;
localforage.setItem = async <T>(key: string, value: T) => { memory.set(key, value); return value; };
localforage.keys = async () => [...memory.keys()];
const downloaded: string[] = [];
globalThis.window = { location: { href: 'http://localhost/' }, kardsDesktop: { fetchCardImage: async (url: string) => { downloaded.push(url); return avifData; } } } as unknown as Window & typeof globalThis;
globalThis.fetch = (async (url: URL) => { assert.equal(String(url), 'http://localhost/data/cards.json'); return Response.json({ cards }); }) as typeof fetch;
memory.set(`kards_card_image_v1_54_zh-Hans_${base.importId}`, 'old-v54-cache');
await Promise.all([cacheCardImage(base, 'zh-Hans'), cacheCardImage(base, 'zh-Hans'), cacheCardImage(base, 'zh-Hans', 'thumbnail')]);
assert.deepEqual(downloaded, [base.imageUrl, base.thumbUrl], 'concurrent full/thumbnail requests deduplicate by URL and bypass stale v54');
assert.equal(await getCachedCardImage(base), avifData);
assert.equal(await getCachedCardImage(base, 'zh-Hans', 'thumbnail'), avifData);
await cacheCardImage(base, 'zh-Hans');
assert.equal(downloaded.length, 2, 'repeated requests sharing a URL share the cache');
const updated = { ...base, imageUrl: base.imageUrl!.replace('/v53/', '/v55/') };
assert.equal(await getCachedCardImage(updated), null);
await cacheCardImage(updated, 'zh-Hans');
assert.equal(downloaded[2], updated.imageUrl);
assert.equal(downloaded.filter(url => url === base.thumbUrl).length, 1, 'unchanged thumbnail URL is reused');
assert.equal(await getCachedCardImage(base), avifData, 'rollback can still use the earlier image cache');
assert.equal(memory.get(`kards_card_image_v1_54_zh-Hans_${base.importId}`), 'old-v54-cache');
const oldCard = { ...base, imageUrl: undefined, thumbUrl: undefined };
assert.equal(await getCachedCardImage(oldCard), 'old-v54-cache', 'legacy snapshots retain their exact old cache');
assert.equal(await getCachedCardImage(oldCard, 'zh-Hans', 'thumbnail'), avifData, 'legacy strips use the bundled true thumbnail, never the full-image fallback');
const thumbKey = `kards_card_image_v2_${base.importId}_${encodeURIComponent(base.thumbUrl!)}`;
memory.delete(thumbKey);
assert.equal(await getCachedCardImage(oldCard, 'zh-Hans', 'thumbnail'), null, 'a missing thumbnail does not read a full card cache');
await cacheCardImage(oldCard, 'zh-Hans', 'thumbnail');
assert.equal(downloaded.at(-1), base.thumbUrl, 'legacy cards fetch the real thumbnail without applying new metadata');
assert.equal(oldCard.thumbUrl, undefined, 'image resolution must not mutate the active legacy catalogue');
assert.equal(cardImageUrl({ ...base, thumbUrl: undefined }, 'zh-Hans', 'thumbnail'), base.thumbUrl, 'full-only metadata still resolves an independent /thumb/ URL');
const noThumbnail = { ...oldCard, cardId: 'missing-from-bundled-index', importId: '??' };
memory.set('kards_card_image_v1_54_zh-Hans_??', 'full-only');
assert.equal(await getCachedCardImage(noThumbnail, 'zh-Hans', 'thumbnail'), null);
await assert.rejects(() => cacheCardImage(noThumbnail, 'zh-Hans', 'thumbnail'), /缺少缩略图地址/);
const beforeEnglish = downloaded.length;
await Promise.all([cacheCardImage(base, 'en-EN'), cacheCardImage(base, 'en-EN', 'thumbnail')]);
assert.equal(downloaded[beforeEnglish], cardImageUrl(base, 'en-EN'));
assert.equal(downloaded[beforeEnglish + 1], cardImageUrl(base, 'en-EN', 'thumbnail'));
const updatedThumb = { ...base, thumbUrl: base.thumbUrl!.replace('/v53/', '/v55/') };
assert.equal(await getCachedCardImage(updatedThumb, 'zh-Hans', 'thumbnail'), null);
let failThumbnail = true;
window.kardsDesktop!.fetchCardImage = async (url: string) => {
  downloaded.push(url);
  if (failThumbnail && url === updatedThumb.thumbUrl) throw new Error('fixture thumbnail failure');
  return avifData;
};
assert.equal(await cacheCardImage(updatedThumb, 'zh-Hans'), avifData, 'a failed companion does not hide the available full image');
await assert.rejects(() => cacheCardImage(updatedThumb, 'zh-Hans', 'thumbnail'), /thumbnail failure/);
let inventory = await readCardImageCache([base, updatedThumb, veteran, noThumbnail], 'zh-Hans');
assert.deepEqual(inventory.entries.map(entry => entry.status), ['cached', 'failed', 'missing', 'failed']);
assert.equal(inventory.entries[1].full.status, 'cached');
assert.equal(inventory.entries[1].thumbnail.error?.message, 'fixture thumbnail failure');
assert.ok(inventory.entries[1].thumbnail.error?.at);
assert.equal(inventory.entries[3].full.status, 'cached');
assert.equal(inventory.entries[3].thumbnail.status, 'failed');
assert.ok(inventory.groups.some(group => group.language === 'en-EN' && group.full === 1 && group.thumbnail === 1));
assert.ok(inventory.groups.some(group => group.language === 'zh-Hans' && group.full >= 2));
failThumbnail = false;
const beforeRetry = downloaded.length;
await cacheCardImage(updatedThumb, 'zh-Hans', 'thumbnail');
assert.deepEqual(downloaded.slice(beforeRetry), [updatedThumb.thumbUrl], 'retry downloads only the missing thumbnail');
inventory = await readCardImageCache([updatedThumb, veteran], 'zh-Hans');
assert.equal(inventory.entries[0].status, 'cached', 'successful retry clears failure');
assert.equal(inventory.entries[0].thumbnail.error, undefined);
assert.ok(!Object.keys(memory.get('kards_card_image_failures_v1') as object).some(key => key.includes(encodeURIComponent(updatedThumb.thumbUrl!))));
assert.equal((await readCardImageCache([base], 'fr-FR')).entries[0].status, 'missing', 'unattempted languages are missing, not failed');
await recordImageCacheBatch([base, veteran], 'en-EN');
const { startImageDownload } = await import('./imageDownloads');
await startImageDownload([base], 'en-EN', true);
assert.deepEqual((await readCardImageCache([base, veteran], 'en-EN')).batch?.importIds, [base.importId, veteran.importId], 'retry retains the original batch scope');
await startImageDownload([veteran], 'zh-Hans');
assert.deepEqual((await readCardImageCache([base, veteran], 'zh-Hans')).batch?.importIds, [veteran.importId]);
assert.equal(await getCachedCardImage(base, 'zh-Hans', 'thumbnail'), avifData, 'old thumbnails survive for rollback');
console.log('Kardsplayer image and card-detail tests passed: independent legacy thumbnails, paired cache, persisted failure/partial inventory/retry, batch scope, catalogue URLs, AVIF MIME, veteran details');
